param([string]$Project = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'
$read = Join-Path $Project 'docs/evidence/wowhead-forever-profession-sources.txt'
$catalog = [IO.File]::ReadAllText((Join-Path $Project 'src/Data/Catalog.lua'))
$snapshot = @{}
foreach ($line in [IO.File]::ReadAllLines($read)) {
    $prof,$categories,$ids = $line.Split('|')
    foreach ($id in $ids.Split(',')) { $snapshot["$prof/$id"] = $categories }
}
$parts = [regex]::Split($catalog,'\[(\d+)\]=\{(?=\[\d+\]=\{\["example"\])')
$rows = foreach ($i in 1..($parts.Count-2)) {
    if ($i % 2 -eq 0) { continue }
    $prof = $parts[$i]
    foreach ($m in [regex]::Matches($parts[$i+1],'\[(\d+)\]=\{\["(?:example|green)"\]')) {
        $id = $m.Groups[1].Value
        $key = "$prof/$id"
        $category = $snapshot[$key]
        $status = if (!$category) {'absent'} elseif ($category -eq '?') {'unspecified'} else {'listed'}
        [pscustomobject]@{profession=$prof;spell=$id;status=$status;source=$category}
    }
}
if (!$rows -or $rows.Count -lt 2000) { throw 'Unexpected or incomplete catalogue format' }
$rows | Export-Csv -NoTypeInformation -Encoding UTF8 -Path (Join-Path $Project 'docs/evidence/forever-recipe-comparison.csv')
$lua = [Collections.Generic.List[string]]::new()
$lua.Add('-- Wowhead Forever profession lists. Generated by tools/Compare-ForeverRecipeSources.ps1.')
$lua.Add('local _,app=...')
$lua.Add('local function apply(categories,ids)')
$lua.Add('    for _,id in ipairs(ids)do')
$lua.Add('        local row=app.accessData[id]')
$lua.Add('        if row then row.categories=categories end')
$lua.Add('    end')
$lua.Add('end')
foreach ($group in ($rows | Where-Object status -eq listed | Group-Object source | Sort-Object Name)) {
    $types = foreach ($type in $group.Name.Split(',')) {
        $name = $type.Trim().ToLowerInvariant()
        if ($name -eq 'fished') {$name='fishing'}
        if ($name -eq 'pickpocketed') {$name='pickpocket'}
        "'$name'"
    }
    $lua.Add(('apply({'+($types -join ',')+'},{'+(($group.Group.spell | Sort-Object {[int]$_} -Unique) -join ',')+'})'))
}
[IO.File]::WriteAllLines((Join-Path $Project 'src/Data/ForeverRecipeSources.lua'),$lua,[Text.UTF8Encoding]::new($false))
$rows | Group-Object status | Select-Object Name,Count
